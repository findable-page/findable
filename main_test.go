const recorded = `{
  "seo": {"score": 92, "passed": 2, "total": 3, "checks": [
    {"id": "title", "label": "Title is \"short\"", "pass": true},
    {"id": "hreflang", "label": "No hreflang", "pass": false},
    {"id": "amp", "label": "AMP", "pass": false, "applicable": false}]},
  "aeo": {"score": 90, "passed": 1, "total": 1, "checks": [{"id": "faq", "label": "FAQ schema", "pass": true}]},
  "geo": {"score": 84, "passed": 0, "total": 1, "checks": [{"id": "quotes", "label": "No expert quotes", "pass": false}]},
  "cwv": {"checks": []}
}`

func decode(t *testing.T) scan {
	t.Helper()
	var s scan
	if err := json.Unmarshal([]byte(recorded), &s); err != nil {
		t.Fatal(err)
	}
	return s
}

func TestOverallWeightsSEOHalfAndRounds(t *testing.T) {
	// 0.5*92 + 0.25*90 + 0.25*84 = 89.5, which rounds up to 90
	if got := overall(decode(t)); got != 90 {
		t.Fatalf("overall = %d, want 90", got)
	}
}

func TestMissingScoreCountsAsZero(t *testing.T) {
	if got := overall(scan{}); got != 0 {
		t.Fatalf("overall of empty scan = %d, want 0", got)
	}
}

func TestStatusDistinguishesPassFailAndNotApplicable(t *testing.T) {
	checks := decode(t).SEO.Checks
	for i, want := range []string{"PASS", "FAIL", "N/A"} {
		if got := status(checks[i]); got != want {
			t.Errorf("%s: status = %s, want %s", checks[i].ID, got, want)
		}
	}
}

func TestFailedCountIgnoresPassAndNA(t *testing.T) {
	if got := failedCount(decode(t)); got != 2 {
		t.Fatalf("failedCount = %d, want 2", got)
	}
}

func TestCSVHasBOMCategoriesAndQuotedLabels(t *testing.T) {
	lines := strings.Split(csv("example.com", decode(t)), "\n")
	if !strings.HasPrefix(lines[0], "\xef\xbb\xbfSEO/AEO/GEO Report,example.com,") {
		t.Errorf("header row = %q", lines[0])
	}
	for _, want := range []string{
		"Overall,90,,",
		"SEO,92,2,3",
		"AEO,90,1,1",
		"GEO,84,0,1",
		`title,SEO,PASS,"Title is ""short"""`,
		`hreflang,SEO,FAIL,"No hreflang"`,
		`amp,SEO,N/A,"AMP"`,
		`quotes,GEO,FAIL,"No expert quotes"`,
	} {
		if !contains(lines, want) {
			t.Errorf("csv is missing row %q", want)
		}
	}
	if contains(lines, "CWV,0,0,0") {
		t.Error("CWV row must be left out when there is no CWV score")
	}
}

func TestCrawlCSVGeneratesCorrectFormat(t *testing.T) {
	s := decode(t)
	pages := []crawledPage{
		{url: "https://example.com", scan: s},
		{url: "https://example.com/about", scan: s},
	}
	lines := strings.Split(crawlCSV("example.com", pages), "\n")
	if !strings.HasPrefix(lines[0], "\xef\xbb\xbfSite Crawl Report,example.com,") {
		t.Errorf("header row = %q", lines[0])
	}
	for _, want := range []string{
		"Generated by,seoscore.tools,",
		"Pages scanned,2,",
		"URL,SEO Score,AEO Score,GEO Score,Overall,Failed Checks",
		`"https://example.com",92,90,84,90,2`,
		`"https://example.com/about",92,90,84,90,2`,
		"All Failed Checks,,,,,",
		"URL,Check ID,Category,Description",
		`"https://example.com",hreflang,SEO,"No hreflang"`,
		`"https://example.com",quotes,GEO,"No expert quotes"`,
		`"https://example.com/about",hreflang,SEO,"No hreflang"`,
		`"https://example.com/about",quotes,GEO,"No expert quotes"`,
	} {
		if !contains(lines, want) {
			t.Errorf("crawl csv missing row %q", want)
		}
	}
}

func TestMatchesWebsiteCsvExportExact(t *testing.T) {
	raw, err := os.ReadFile("testdata/reports/raw/04-geo-research.json")
	if err != nil {
		t.Skip("fixture not available")
	}
	var s scan
	if err := json.Unmarshal(raw, &s); err != nil {
		t.Fatal(err)
	}
	goCsv := csv("declined-parcel-saver-employment.trycloudflare.com", s)
	webCsv, err := os.ReadFile("/tmp/web_report.csv")
	if err != nil {
		t.Skip("web csv not generated")
	}
	// Regenerate webCsv for today using testdata/web_csv.js or normalize the date in the first row
	normalizeDate := func(s string) string {
		lines := strings.Split(s, "\n")
		if len(lines) > 0 && strings.HasPrefix(lines[0], "\xef\xbb\xbfSEO/AEO/GEO Report") {
			parts := strings.Split(lines[0], ",")
			if len(parts) == 3 {
				parts[2] = "DATE"
				lines[0] = strings.Join(parts, ",")
			}
		}
		return strings.Join(lines, "\n")
	}

	normGo := normalizeDate(goCsv)
	normWeb := normalizeDate(string(webCsv))

	if normGo != normWeb {
		for i := 0; i < len(normGo) && i < len(normWeb); i++ {
			if normGo[i] != normWeb[i] {
				t.Fatalf("diff at byte %d: go=%q (code %d), web=%q (code %d)\ncontext:\ngo: %q\nweb: %q",
					i, normGo[i], normGo[i], normWeb[i], normWeb[i],
					normGo[max(0, i-20):min(len(normGo), i+20)],
					normWeb[max(0, i-20):min(len(normWeb), i+20)])
			}
		}
		t.Fatalf("csv output differs from website export:\nGo len=%d, Web len=%d", len(normGo), len(normWeb))
	}
}

func contains(lines []string, want string) bool {
	for _, l := range lines {
		if l == want {
			return true
		}
	}
	return false
}
