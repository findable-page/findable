package report

import (
	"strconv"
	"strings"
	"time"

	"github.com/nadimtuhin/seoscore-cli/internal/audit"
)

const DateLayout = "2006-01-02"

func quote(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

func CSV(host string, s audit.Scan) string {
	var b strings.Builder
	row := func(cells ...string) { b.WriteString(strings.Join(cells, ",") + "\n") }
	b.WriteString("\xef\xbb\xbf")
	row("SEO/AEO/GEO Report", host, time.Now().Format(DateLayout))
	row("Generated by", "seoscore.tools", "")
	row("")
	row("Category", "Score", "Passed", "Total")
	row("Overall", strconv.Itoa(audit.Overall(s)), "", "")
	for _, c := range s.Scored() {
		row(c.Name, audit.ScoreText(c.Cat), strconv.Itoa(c.Cat.Passed), strconv.Itoa(c.Cat.Total))
	}
	if s.CWV.Score != nil {
		row("CWV", audit.ScoreText(s.CWV), strconv.Itoa(s.CWV.Passed), strconv.Itoa(s.CWV.Total))
	}
	row("")
	row("Check ID", "Category", "Status", "Description")
	for _, c := range append(s.Scored(), audit.NamedCategory{Name: "CWV", Cat: s.CWV}) {
		for _, k := range c.Cat.Checks {
			row(k.ID, c.Name, audit.Status(k), quote(k.Label))
		}
	}
	return b.String()
}

func CrawlCSV(host string, pages []audit.Page) string {
	var b strings.Builder
	row := func(cells ...string) { b.WriteString(strings.Join(cells, ",") + "\n") }
	b.WriteString("\xef\xbb\xbf")
	date := time.Now().Format(DateLayout)
	row("Site Crawl Report", host, date)
	row("Generated by", "seoscore.tools", "")
	row("Pages scanned", strconv.Itoa(len(pages)), "")
	row("")
	row("URL", "SEO Score", "AEO Score", "GEO Score", "Overall", "Failed Checks")
	for _, p := range pages {
		row(quote(p.URL), audit.ScoreText(p.Scan.SEO), audit.ScoreText(p.Scan.AEO), audit.ScoreText(p.Scan.GEO), strconv.Itoa(audit.Overall(p.Scan)), strconv.Itoa(audit.FailedCount(p.Scan)))
	}
	row("")
	row("All Failed Checks", "", "", "", "", "")
	row("URL", "Check ID", "Category", "Description")
	for _, p := range pages {
		for _, c := range p.Scan.Scored() {
			for _, k := range c.Cat.Checks {
				if audit.Status(k) == audit.StatusFail {
					row(quote(p.URL), k.ID, c.Name, quote(k.Label))
				}
			}
		}
	}
	return b.String()
}
